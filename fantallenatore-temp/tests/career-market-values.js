'use strict';
const assert=require('node:assert/strict');
const {createRuntime}=require('./helpers/season-runtime');
const api=createRuntime('market-regression');
const players=api.players(),state=api.getState();
const initial=players.map(p=>p.quotation);
api.refreshMarket();
assert.deepEqual(players.map(p=>p.quotation),initial,'Initial-season quotes preserved');
const meret=players.find(p=>p.name==='Meret');
meret.ovr=96;
const reserve={id:'market-test-reserve',name:'Tambo peppe',role:'P',club:meret.club,ovr:90,quotation:21,fvm:60};
players.push(reserve);
state.career.seasonNumber=4;
api.refreshMarket();
assert(meret.quotation>reserve.quotation*3);
assert(api.value(meret)>api.value(reserve)*3);
const quote=meret.quotation,value=api.value(meret);
api.refreshMarket();
assert.equal(meret.quotation,quote);
assert.equal(api.value(meret),value);
state.season.playerStatus[meret.id]={injuryUntil:38};
api.refreshMarket();
assert.equal(meret.quotation,quote,'Temporary availability must not change structural value');
reserve.club='market-test-club';
api.refreshMarket();
assert(reserve.quotation>2,'A transfer to a starter position must raise reserve value');
console.log('OK: initial season, Meret/reserve quotes and CPU values, idempotence, temporary status, club transfer.');
