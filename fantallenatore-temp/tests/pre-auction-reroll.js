'use strict';
const assert=require('node:assert');
const {createRuntime}=require('./helpers/season-runtime');
const api=createRuntime('pre-auction-reroll');
const state=api.getState();
assert.equal(api.rulesItem().currency,'fp');assert.equal(api.rulesItem().cost,25);
state.career.fantapoints=24;assert.equal(api.rulesBuy(),false);
state.career.fantapoints=50;const euros=state.career.euros;
assert.equal(api.rulesBuy(),true);assert.equal(state.career.fantapoints,25);assert.equal(state.career.euros,euros);
const draft=api.rulesSetup(2);const old=JSON.stringify(draft.leagueRules);
assert.equal(api.rulesReroll(),true);assert.notEqual(JSON.stringify(draft.leagueRules),old);
assert.equal(draft.leagueRules.selectedCategories.length,3);
assert.equal(state.season.consumables.inventory.cons_reroll_rules,1);
assert.equal(draft.carryoverConsumables.cons_reroll_rules,1);
const saved=JSON.stringify(state.nextSeasonFlow.preAuctionRules);
const snapshot=api.storageSnapshot();assert.equal(JSON.stringify(snapshot.nextSeasonFlow.preAuctionRules),saved);
api.rulesClose();assert.equal(api.rulesReroll(),false);
const reopened=api.rulesResume();assert.equal(JSON.stringify(reopened.leagueRules),saved);
reopened.auction={};assert.equal(api.rulesReroll(),false);delete reopened.auction;
assert.equal(api.rulesReroll(),true);assert.equal(state.season.consumables.inventory.cons_reroll_rules,0);
assert.equal(api.rulesReroll(),false);
console.log('OK: acquisto solo FP, consumo, nuove regole, salvataggio e riapertura, blocco ad asta iniziata e senza oggetti.');
