'use strict';
const assert=require('node:assert');
const {createRuntime}=require('./helpers/season-runtime');
const api=createRuntime('admin-one-shot');const state=api.adminPowerSetup();
const admin=state.managers.find(m=>m.profile.archetype==='admin');assert(admin);
const ranked=api.players().map(player=>({player,score:api.adminPowerScore(admin,player)})).filter(p=>p.score>0).sort((a,b)=>b.score-a.score);
const best=ranked[0].player,weak=ranked.at(-1).player;
function auction(player=best){state.auction={playerId:player.id,nominatorId:'user',highBidderId:'user',price:140,activeIds:state.managers.map(m=>m.id),log:[]};}
auction(weak);assert.equal(api.adminPowerTry(),false,'Conserva il potere per un top');
auction();state.career.division=2;assert.equal(api.adminPowerTry(),false);state.career.division=1;
for(const type of ['bundle','sealed','mystery']){state.auction.arcade={type};assert.equal(api.adminPowerTry(),false);}delete state.auction.arcade;
state.auction.blockedCpuIds=[admin.id];assert.equal(api.adminPowerTry(),false);delete state.auction.blockedCpuIds;
state.winterMarketFlow={stage:'auction'};assert.equal(api.adminPowerTry(),false);delete state.winterMarketFlow;
const budget=admin.budget,slots=admin.roster.length;
api.adminPowerFast();assert.equal(state.adminOneShot.used,true);assert.equal(admin.budget,budget-1);assert.equal(admin.roster.length,slots+1);assert.equal(admin.roster.at(-1).price,1);
assert.equal(state.auction.highBidderId,admin.id);assert.equal(state.auction.adminOneShotForced,true);
assert.equal(api.storageSnapshot().adminOneShot.used,true,'Uso persistente nel salvataggio');
auction(ranked[1].player);assert.equal(api.adminPowerTry(),false,'Un solo uso per asta');
const next=api.adminPowerSetup();assert.equal(next.adminOneShot,undefined,'Nuova stagione/asta ripristina il potere');
const nextAdmin=next.managers.find(m=>m.profile.archetype==='admin');
next.auction={playerId:best.id,highBidderId:'user',price:10,activeIds:next.managers.map(m=>m.id),log:[]};
nextAdmin.budget=0;assert.equal(api.adminPowerTry(),false);
nextAdmin.budget=500;nextAdmin.roster=Array.from({length:25},()=>({...best,price:1}));assert.equal(api.adminPowerTry(),false,'Rispetta limite rosa');
console.log('OK: Admin solo Serie A, scelta top, blocchi/eventi, acquisto atomico a 1, un uso persistente e limiti rosa/budget.');
