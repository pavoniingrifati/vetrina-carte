'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'js/domains/manifest.json'),'utf8'));
const clockEntry=manifest.find(entry=>entry.name==='auction-clock');
assert(!clockEntry.dependencies.includes('awardAuction')&&!clockEntry.dependencies.includes('renderAuctionRoomList'),'Clock must not depend on application consumers');
assert(clockEntry.dependencies.includes('auctionClockEvents'));
const clockSource=fs.readFileSync(path.join(root,clockEntry.file),'utf8');
assert.deepEqual([...new Set([...clockSource.matchAll(/\$runtime\.([\w$]+)/g)].map(match=>match[1]))].sort(),clockEntry.dependencies);
let tick,cleared=false,now=100;
const context=vm.createContext({window:{},Date:{now:()=>now},setInterval:fn=>(tick=fn,1),clearInterval:()=>{cleared=true;},clearTimeout:()=>{}});
for(const file of ['js/auction-clock-events.js','js/domains/auction-clock.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const events=context.window.FantaAuctionClockEvents.create(),history=[];
const stop=events.subscribe('tick',()=>history.push('render'));
events.subscribe('expired',()=>{assert(cleared,'Timers stop before the application handles expiration');history.push('award');});
const runtime={auctionClockEvents:events,state:{auction:{deadlineAt:200}},$:()=>null,cpuReactionTimers:[],autocompleteMode:false};
const clock=context.window.FantaDomains['auction-clock'].create(runtime);
assert(!('awardAuction' in runtime)&&!('renderAuctionRoomList' in runtime));
clock.startCountdownTicker();assert.deepEqual(history,['render']);
tick();assert.deepEqual(history,['render','render']);
now=200;tick();assert.deepEqual(history,['render','render','render','award']);
assert.equal(runtime.countdownTimer,null);
stop();events.publish('tick');assert.equal(history.length,4,'Unsubscribed listeners receive no events');
runtime.state=null;clock.startCountdownTicker();tick();assert.equal(runtime.countdownTimer,null);
assert.throws(()=>events.publish('unknown'),/Unknown auction clock event/);
assert.throws(()=>events.subscribe('tick',null),/Listener required/);
const other=context.window.FantaAuctionClockEvents.create();other.publish('expired');assert.equal(history.length,4,'Channels are isolated per application instance');
console.log('OK: auction clock runs without view or award controllers; synchronous events preserve update order, timer cleanup and unsubscribe.');
