'use strict';
const assert=require('node:assert/strict');
const {createRuntime}=require('./helpers/season-runtime');
const api=createRuntime('admin-76');
const state=api.getState();
state.leagueRules={firstGoalThreshold:65};
const card=api.adminTemplate('admin-goal-threshold-76',2);
assert.equal(card.rarity,'epic');
state.season.adminRules['2']={triggered:true,resolved:true,selectedOption:card};
assert.equal(api.rules(2).firstGoalThreshold,76);
for(const [points,goals] of [[65,0],[75.99,0],[76,1],[81.99,1],[82,2],[88,3]])assert.equal(api.goals(points,2),goals);
assert.equal(api.rules(3).firstGoalThreshold,65);
assert.equal(api.goals(65,3),1);
assert.equal(state.leagueRules.firstGoalThreshold,65);
const restored=api.parseSave(JSON.stringify(api.storageSnapshot()));
Object.assign(state,restored);
assert.equal(api.rules(2).firstGoalThreshold,76);
assert.equal(api.rules(3).firstGoalThreshold,65);
console.log('OK: epic 76 threshold, goal boundaries, next-day reset and save reload.');
